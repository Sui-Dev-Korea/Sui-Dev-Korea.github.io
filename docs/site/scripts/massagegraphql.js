const fs = require("fs");
const path = require("path");

const checkpointPath = path.resolve(
  __dirname,
  "../../content/references/sui-api/sui-graphql/beta/reference/types/objects/checkpoint.mdx",
);

// Keep post-processing idempotent so reruns do not create noisy diffs.
function patchFile(filePath, transform) {
  const content = fs.readFileSync(filePath, "utf8");
  const next = transform(content);

  if (next !== content) {
    fs.writeFileSync(filePath, next, "utf8");
    return true;
  }

  return false;
}

// Docusaurus i18n generates translation keys from sidebar labels.
// The GraphQL docs include two "Directives" categories under the same sidebar,
// so we inject stable keys to prevent duplicate translation-key collisions.
function ensureCategoryKey(filePath, keyValue) {
  return patchFile(filePath, (content) => {
    if (/^key:\s*/m.test(content)) {
      return content.replace(/^key:\s*.*$/m, `key: ${keyValue}`);
    }

    if (/^label:\s*/m.test(content)) {
      return content.replace(/^label:\s*.*$/m, (labelLine) => `${labelLine}\nkey: ${keyValue}`);
    }

    return `key: ${keyValue}\n${content}`;
  });
}

const checkpointPatched = patchFile(checkpointPath, (content) =>
  content.replace(
    /\[([^\]]*)\]\([^)]*query\.mdx\)/g,
    "$1",
  ),
);

// These files are generated by graphql-to-doc during build.
const operationsDirectivesCategoryPath = path.resolve(
  __dirname,
  "../../content/references/sui-api/sui-graphql/beta/reference/operations/directives/_category_.yml",
);

const typesDirectivesCategoryPath = path.resolve(
  __dirname,
  "../../content/references/sui-api/sui-graphql/beta/reference/types/directives/_category_.yml",
);

const operationsCategoryPatched = ensureCategoryKey(
  operationsDirectivesCategoryPath,
  "operations-directives",
);

const typesCategoryPatched = ensureCategoryKey(
  typesDirectivesCategoryPath,
  "types-directives",
);

if (checkpointPatched) {
  console.log("✅ Patched query link in checkpoint.mdx");
} else {
  console.log("ℹ️ Query link in checkpoint.mdx already patched");
}

if (operationsCategoryPatched || typesCategoryPatched) {
  console.log("✅ Added stable sidebar keys for duplicated Directives categories");
} else {
  console.log("ℹ️ Directives category sidebar keys already set");
}
